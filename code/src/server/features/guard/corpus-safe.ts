export type Expect = "allow" | "ask" | "deny";
export interface CorpusCase {
  cmd: string;
  expect: Expect;
}

export function cases(expect: Expect, cmds: string[]): CorpusCase[] {
  return cmds.map((cmd) => ({ cmd, expect }));
}

